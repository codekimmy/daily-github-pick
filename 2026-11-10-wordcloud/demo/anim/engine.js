const IMG = {};
function loadImgs(base, names) {
  return Promise.all(names.map(n => { const im = new Image(); im.src = `${base}/${n}`; IMG[n] = im; return im.decode().catch(() => console.log('missing', n)); }));
}
// 그림을 상자 안에 비율 유지해 맞춤. 테두리 상자 포함
function pic(n, x, y, w, h, a = 1, frame = true, label) {
  if (a <= 0) return; const im = IMG[n]; if (!im) return; const k = Math.min(w / im.width, h / im.height), dw = im.width * k, dh = im.height * k, dx = x + (w - dw) / 2, dy = y + (h - dh) / 2;
  if (frame) box(dx - 4, dy - 4, dw + 8, dh + 8, 10, null, '#30363d', a, 2);
  ctx.save(); ctx.globalAlpha *= a; ctx.drawImage(im, dx, dy, dw, dh); ctx.restore();
  if (label) text(label, x + w / 2, dy + dh + 34, 26, SUB, 700, 'center', a);
  return [dx, dy, dw, dh];
}
